# ============================================================
# Helper Functions
# ============================================================


def get_sections():
    """
    Return all major aptitude sections.
    """

    return list(TOPICS.keys())


def get_available_topics(section=None):
    """
    Return topics.

    If section is provided:
        return topics under that section.

    If section is not provided:
        return all topics.
    """

    if section:

        if section not in TOPICS:
            return []

        return list(TOPICS[section].keys())

    all_topics = []

    for section_name in TOPICS:

        all_topics.extend(
            TOPICS[section_name].keys()
        )

    return all_topics


def get_topic_types(topic):
    """
    Find question types for a topic.
    """

    for section in TOPICS:

        if topic in TOPICS[section]:

            return TOPICS[section][topic]["types"]

    return []


def get_topic_section(topic):
    """
    Find which major section a topic belongs to.
    """

    for section in TOPICS:

        if topic in TOPICS[section]:

            return section

    return None